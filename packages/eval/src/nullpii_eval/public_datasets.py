def _load_bigcode_pii(max_samples: int | None) -> PublicDataset:
    """bigcode/bigcode-pii-dataset — gated. Code files with labeled
    secrets, emails, IPs. Best signal for "dev pastes prod code"
    use case. Requires `HF_TOKEN` env var.
    """
    from datasets import load_dataset

    # Single split typically `train`. Schema: {"text", "fragments":
    # [{"position": [start, end], "category": ...}]} (varies by mirror).
    split = "train" if max_samples is None else f"train[:{max_samples}]"
    ds = load_dataset("bigcode/bigcode-pii-dataset", split=split)
    samples: list[Sample] = []
    for row in ds:
        text = str(row.get("text") or row.get("content") or "")
        if not text:
            continue
        spans: list[Span] = []
        fragments = row.get("fragments") or row.get("annotations") or []
        for f in fragments:
            cat = str(f.get("category") or f.get("label") or "").upper()
            mapped = _BIGCODE_PII_LABELS.get(cat)
            if mapped is None:
                continue
            pos = f.get("position") or [f.get("start"), f.get("end")]
            if not pos or pos[0] is None or pos[1] is None:
                continue
            spans.append(Span(mapped, int(pos[0]), int(pos[1])))
        samples.append(Sample(text=text, spans=tuple(spans)))
    return PublicDataset(
        name="bigcode/bigcode-pii-dataset",
        citation="BigCode. PII in code dataset (gated).",
        samples=tuple(samples),
    )


