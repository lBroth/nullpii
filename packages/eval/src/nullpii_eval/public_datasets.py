def _load_presidio_synthetic(max_samples: int | None) -> PublicDataset:
    try:
        from presidio_evaluator.data_generator import PresidioSentenceFaker
    except ImportError as e:
        raise ImportError(
            "presidio_evaluator not installed; "
            "run `pip install presidio-evaluator` to use this dataset",
        ) from e

    # Faker is generative — there is no "full" split. For `None`,
    # default to 5000 (release benchmark size); cap honored otherwise.
    n = max_samples if max_samples is not None else 5000
    faker = PresidioSentenceFaker(locale="en_US", lower_case_ratio=0.05)
    rows = faker.generate_new_fake_sentences(num_samples=n)
    samples: list[Sample] = []
    for r in rows[:n]:
        text = str(getattr(r, "fake", getattr(r, "full_text", "")))
        spans_raw = list(getattr(r, "spans", None) or [])
        spans = []
        for s in spans_raw:
            label = _map_presidio_entity_to_nullpii(str(getattr(s, "entity_type", "")))
            if label is None:
                continue
            spans.append(
                Span(
                    label,
                    int(getattr(s, "start_position", 0)),
                    int(getattr(s, "end_position", 0)),
                ),
            )
        samples.append(Sample(text=text, spans=tuple(spans)))
    return PublicDataset(
        name="presidio-synthetic",
        citation="Presidio Evaluator (PresidioSentenceFaker) synthetic generator.",
        samples=tuple(samples),
    )


