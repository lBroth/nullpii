def _strip_index(label: str) -> str:
    """Isotonic labels are like `CITY_1`, `FIRSTNAME_2` — strip the trailing `_<n>`."""
    parts = label.rsplit("_", 1)
    if len(parts) == 2 and parts[1].isdigit():
        return parts[0]
    return label


def _load_isotonic(
    max_samples: int | None, *, lang: str = "en", row_offset: int = 0,
) -> PublicDataset:
    """Isotonic/pii-masking-200k — open mirror of ai4privacy's PII set.

    Multi-lingual (`language` field). Filtered by `lang`. Uses `unmasked_text`
    + `span_labels` (list of `[start, end, label]`).

    `max_samples=None` → load the entire `train` split, no cap.
    `row_offset` slices the underlying train split BEFORE language filtering.
    Use it to build a held-out split disjoint from the slice the model was
    trained on. Training default prefetched 200000 rows for the 20k-per-locale
    cap, so pass `row_offset=200000` for a clean held-out split.
    """
    import ast
    import sys

    from datasets import load_dataset

    if max_samples is None:
        slice_spec = "train" if row_offset == 0 else f"train[{row_offset}:]"
        ds = load_dataset("Isotonic/pii-masking-200k", split=slice_spec)
    else:
        # ~21% of dataset is the smallest locale (en), so 10× buffer
        # guarantees enough samples after language filtering.
        prefetch = max(max_samples * 10, 2000)
        slice_spec = f"train[{row_offset}:{row_offset + prefetch}]"
        ds = load_dataset("Isotonic/pii-masking-200k", split=slice_spec)
    samples: list[Sample] = []
    for row in ds:
        if max_samples is not None and len(samples) >= max_samples:
            break
        if str(row.get("language", "")).lower() != lang.lower():
            continue  # locale filter, not an error
        text = str(row.get("unmasked_text") or "")
        if not text:
            # Upstream sometimes ships rows with empty unmasked_text.
            # Refuse to silently drop — schema regression should be loud.
            raise ValueError(
                f"[isotonic/{lang}] row has empty unmasked_text "
                f"(row keys: {list(row.keys())})",
            )
        span_labels_raw = row.get("span_labels")
        if isinstance(span_labels_raw, str):
            try:
                span_labels = ast.literal_eval(span_labels_raw)
            except (ValueError, SyntaxError) as e:
                # Bad row format == upstream schema break. Fail loud
                # so the matrix marks isotonic-{lang} CRASHED rather
                # than silently shipping a sample-thin dataset.
                raise ValueError(
                    f"[isotonic/{lang}] could not parse span_labels: "
                    f"{type(e).__name__}: {e}; raw={span_labels_raw!r}",
                ) from e
        else:
            span_labels = span_labels_raw or []
        spans: list[Span] = []
        for entry in span_labels:
            if not isinstance(entry, (list, tuple)) or len(entry) < 3:
                raise ValueError(
                    f"[isotonic/{lang}] malformed span entry: {entry!r}",
                )
            start, end, raw_label = int(entry[0]), int(entry[1]), str(entry[2])
            if raw_label == "O":
                continue  # explicit "no label" sentinel from upstream
            mapped = _ISOTONIC_LABEL_MAP.get(_strip_index(raw_label).upper())
            if mapped is None:
                continue  # label intentionally outside our 12-class taxonomy
            spans.append(Span(mapped, start, end))
        samples.append(Sample(text=text, spans=tuple(spans)))
    citation = "Isotonic. PII Masking 200k (open mirror of ai4privacy)."
    if row_offset > 0:
        citation += f" Held-out slice (row_offset={row_offset})."
    return PublicDataset(
        name=f"isotonic/pii-masking-200k/{lang}",
        citation=citation,
        samples=tuple(samples),
    )


def _row_to_sample(
    row: dict, *, label_field: str, tokens_field: str, schema: str,
) -> Sample | None:
    tokens = list(row[tokens_field])
    tags_raw = list(row[label_field])
    if not tokens or not tags_raw:
        return None

    if schema == "bio_conll":
        id2tag = ["O", "B-PER", "I-PER", "B-ORG", "I-ORG", "B-LOC", "I-LOC", "B-MISC", "I-MISC"]
    elif schema == "bio_wikiann":
        id2tag = ["O", "B-PER", "I-PER", "B-ORG", "I-ORG", "B-LOC", "I-LOC"]
    else:
        return None

    tags = [id2tag[t] if isinstance(t, int) and 0 <= t < len(id2tag) else "O" for t in tags_raw]

    spans: list[Span] = []
    text_parts: list[str] = []
    cursor = 0
    cur_label: str | None = None
    cur_start: int | None = None
    for tok, tag in zip(tokens, tags):
        if cursor > 0:
            text_parts.append(" ")
            cursor += 1
        tok_start = cursor
        text_parts.append(tok)
        cursor += len(tok)
        if tag == "O":
            if cur_label is not None and cur_start is not None:
                spans.append(_finalize(cur_label, cur_start, tok_start - 1))
                cur_label = None
                cur_start = None
            continue
        prefix, _, raw_label = tag.partition("-")
        mapped = _NER_LABEL_MAP.get(raw_label)
        if mapped is None:
            if cur_label is not None and cur_start is not None:
                spans.append(_finalize(cur_label, cur_start, tok_start - 1))
                cur_label = None
                cur_start = None
            continue
        if prefix == "B" or cur_label != mapped:
            if cur_label is not None and cur_start is not None:
                spans.append(_finalize(cur_label, cur_start, tok_start - 1))
            cur_label = mapped
            cur_start = tok_start

    if cur_label is not None and cur_start is not None:
        spans.append(_finalize(cur_label, cur_start, cursor))

    return Sample(text="".join(text_parts), spans=tuple(spans))


def _finalize(label: str, start: int, end: int) -> Span:
    return Span(label, start, max(end, start + 1))


