"""Loaders for public NER / PII benchmarks.

Each loader returns `(samples, citation)` where samples is a list of
`(text, [Span, ...])` and citation is a stable string for the report.

Datasets:
- `conll2003`     — open. PER / LOC / ORG / MISC. Limited PII coverage,
                    used as a NER sanity check.
- `wikiann`       — open, multi-lingual. PER / LOC / ORG.
- `ai4privacy/pii-masking-300k` — gated; needs `HF_TOKEN`.
- `ai4privacy/pii-masking-400k` — newer ai4privacy release.
- `bigcode/bigcode-pii-dataset` — code+secrets, gated (HF_TOKEN).
- `presidio-synthetic`          — open, generated by Presidio's eval lib.
- `dev-prompts-synthetic`       — local generator, code+logs+tickets
                                  with planted PII (gold-known spans).
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

from .datasets import Sample, Span

DatasetName = Literal[
    "conll2003",
    "wikiann",
    "ai4privacy/pii-masking-300k",
    "ai4privacy/pii-masking-400k",
    "bigcode/bigcode-pii-dataset",
    "presidio-synthetic",
    "isotonic/pii-masking-200k",
    "dev-prompts-synthetic",
    "enron-planted",
    "stackoverflow-planted",
    "thestack-planted",
]


@dataclass(frozen=True, slots=True)
class PublicDataset:
    name: str
    citation: str
    samples: tuple[Sample, ...]


# Map upstream NER labels → our 8 categories. Coarse: CoNLL `PER` is a
# person, `LOC` is treated as private_address (loose mapping for sanity).
_NER_LABEL_MAP = {
    "PER": "private_person",
    "PERSON": "private_person",
    "LOC": "private_address",
    "GPE": "private_address",
    "FAC": "private_address",
    "ORG": None,  # too generic, drop
    "MISC": None,
}


def load(
    name: DatasetName, *, max_samples: int | None = None, locale: str = "en",
) -> PublicDataset:
    if name == "conll2003":
        return _load_conll(max_samples)
    if name == "wikiann":
        return _load_wikiann(max_samples, lang=locale)
    if name == "ai4privacy/pii-masking-300k":
        return _load_ai4privacy(max_samples)
    if name == "presidio-synthetic":
        return _load_presidio_synthetic(max_samples)
    if name == "isotonic/pii-masking-200k":
        return _load_isotonic(max_samples, lang=locale)
    if name == "ai4privacy/pii-masking-400k":
        return _load_ai4privacy_400k(max_samples)
    if name == "bigcode/bigcode-pii-dataset":
        return _load_bigcode_pii(max_samples)
    if name == "dev-prompts-synthetic":
        return _generate_dev_prompts(max_samples)
    if name == "enron-planted":
        return _load_enron_planted(max_samples)
    if name == "stackoverflow-planted":
        return _load_stackoverflow_planted(max_samples)
    if name == "thestack-planted":
        return _load_thestack_planted(max_samples)
    raise ValueError(f"unknown public dataset: {name}")


def _load_conll(max_samples: int | None) -> PublicDataset:
    from datasets import load_dataset

    ds = load_dataset("conll2003", split="test", trust_remote_code=True)
    samples: list[Sample] = []
    for row in ds:
        if max_samples is not None and len(samples) >= max_samples:
            break
        sample = _row_to_sample(row, label_field="ner_tags", tokens_field="tokens", schema="bio_conll")
        if sample is not None:
            samples.append(sample)
    return PublicDataset(
        name="conll2003",
        citation="Tjong Kim Sang & De Meulder, 2003. CoNLL-2003 NER (test split).",
        samples=tuple(samples),
    )


