def _generate_dev_prompts(max_samples: int | None) -> PublicDataset:
    """Synthetic developer prompt corpus. Templates with planted PII at
    known positions — gold labels are exact (no annotation noise).

    Categories covered: secret, private_email, private_person,
    private_phone, private_address, private_date, account_number.

    `max_samples=None` → 10000 default. Stable RNG (seed=2026).
    """
    import random

    n = 10000 if max_samples is None else max_samples
    rng = random.Random(2026)
    samples: list[Sample] = []
    for _ in range(n):
        template, placeholders = rng.choice(_DEV_PROMPT_TEMPLATES)
        values: dict[str, str] = {}
        for placeholder, _label in placeholders:
            synth = _DEV_PROMPT_SYNTH[placeholder]
            values[placeholder] = synth(rng)
        text_parts: list[str] = []
        spans: list[Span] = []
        cursor = 0
        i = 0
        while i < len(template):
            if template[i] == "{":
                end_brace = template.index("}", i)
                key = template[i + 1:end_brace]
                value = values.get(key)
                if value is None:
                    text_parts.append(template[i:end_brace + 1])
                    cursor += end_brace + 1 - i
                else:
                    label = next(lbl for k, lbl in placeholders if k == key)
                    span_start = cursor
                    text_parts.append(value)
                    cursor += len(value)
                    spans.append(Span(label, span_start, cursor))
                i = end_brace + 1
            else:
                text_parts.append(template[i])
                cursor += 1
                i += 1
        samples.append(Sample(text="".join(text_parts), spans=tuple(spans)))
    return PublicDataset(
        name="dev-prompts-synthetic",
        citation="nullpii synthetic dev-prompts (Apache 2.0). Templates with planted PII.",
        samples=tuple(samples),
    )


# ─── Plant-and-detect loaders ────────────────────────────────────
#
# Real text base + PII planted at known positions. Best signal for
# "developer pastes prod data into LLM" — model has to find PII
# inside realistic noise (code/log/email content), not on clean
# template text. Gold is exact (planting position).
#
# Stable RNG seed=2026 → reproducible. Each loader plants 1-3 PII
# spans per sample at random word boundaries.


def _plant_pii(text: str, n_spans: int, rng) -> tuple[str, list[Span]]:
    """Insert n_spans PII fragments at random word boundaries in `text`.

    Returns (new_text, spans). Spans positions are in the new text.
    """
    if not text:
        return text, []
    # Word-boundary candidate offsets: positions where char is whitespace
    # or text start. Avoid splitting code tokens / urls.
    candidates = [0]
    for i, ch in enumerate(text):
        if ch.isspace():
            candidates.append(i + 1)
    if len(candidates) < 2:
        return text, []
    # Pick distinct insertion offsets sorted ASCENDING. We track a
    # cumulative `shift` for each insertion: the previous insertions
    # (at lower offsets) push later target offsets forward in the
    # growing `new_text`. Recorded span coordinates are in `new_text`,
    # not the original.
    n_spans = min(n_spans, len(candidates) - 1, 5)
    insert_at = sorted(rng.sample(candidates, n_spans))
    spans: list[Span] = []
    new_text = text
    shift = 0
    for off in insert_at:
        placeholder, label = rng.choice(_PLANT_CHOICES)
        synth = _DEV_PROMPT_SYNTH[placeholder](rng)
        real_off = off + shift
        # Surround with spaces if neighbours aren't whitespace, so the
        # PII reads naturally and gold positions are clean.
        prefix = "" if real_off == 0 or new_text[real_off - 1].isspace() else " "
        suffix = "" if real_off >= len(new_text) or new_text[real_off].isspace() else " "
        injected = prefix + synth + suffix
        new_text = new_text[:real_off] + injected + new_text[real_off:]
        span_start = real_off + len(prefix)
        span_end = span_start + len(synth)
        spans.append(Span(label, span_start, span_end))
        shift += len(injected)
    # Sanity check: each span text matches actually-injected synth.
    return new_text, spans


_PLANT_CHOICES: tuple[tuple[str, str], ...] = (
    ("AWS_KEY", "secret"),
    ("OPENAI_KEY", "secret"),
    ("STRIPE_KEY", "secret"),
    ("GH_TOKEN", "secret"),
    ("JWT", "secret"),
    ("PWD", "secret"),
    ("EMAIL", "private_email"),
    ("PHONE", "private_phone"),
    ("ADDRESS", "private_address"),
    ("NAME", "private_person"),
    ("CARD", "account_number"),
    ("ACC", "account_number"),
    ("IP", "private_ip"),
    ("DOB", "private_date"),
)


