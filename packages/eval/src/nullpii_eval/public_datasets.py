def _load_presidio_synthetic(max_samples: int | None) -> PublicDataset:
    import json as _json
    from pathlib import Path as _Path

    # Prefer the frozen static file so F1 is reproducible across
    # presidio-evaluator versions (generator output drifts with package
    # updates even when seed is pinned).
    static = _Path(__file__).resolve().parent.parent.parent / "datasets" / "presidio-synthetic.jsonl"
    if static.exists():
        n = max_samples if max_samples is not None else 5000
        samples: list[Sample] = []
        with static.open(encoding="utf-8") as f:
            for line in f:
                row = _json.loads(line)
                spans = tuple(
                    Span(s["label"], int(s["start"]), int(s["end"]))
                    for s in row["spans"]
                )
                samples.append(Sample(text=row["text"], spans=spans))
                if len(samples) >= n:
                    break
        return PublicDataset(
            name="presidio-synthetic",
            citation="Presidio Evaluator (PresidioSentenceFaker) synthetic generator.",
            samples=tuple(samples),
        )

    try:
        from presidio_evaluator.data_generator import PresidioSentenceFaker
    except ImportError as e:
        raise ImportError(
            "presidio_evaluator not installed; "
            "run `pip install presidio-evaluator` to use this dataset",
        ) from e

    # Faker is generative — there is no "full" split. For `None`,
    # default to 5000 (release benchmark size); cap honored otherwise.
    # Pin the random seed so resumed benches re-evaluate cached
    # predictions against the same gold output. Without this the
    # generator produces a different sample set on each call → F1
    # collapses on re-run.
    n = max_samples if max_samples is not None else 5000
    faker = PresidioSentenceFaker(
        locale="en_US", lower_case_ratio=0.05, random_seed=2026,
    )
    rows = faker.generate_new_fake_sentences(num_samples=n)
    samples: list[Sample] = []
    for r in rows[:n]:
        text = str(getattr(r, "fake", getattr(r, "full_text", "")))
        spans_raw = list(getattr(r, "spans", None) or [])
        spans = []
        for s in spans_raw:
            label = _map_presidio_entity_to_nullpii(str(getattr(s, "entity_type", "")))
            if label is None:
                continue
            spans.append(
                Span(
                    label,
                    int(getattr(s, "start_position", 0)),
                    int(getattr(s, "end_position", 0)),
                ),
            )
        samples.append(Sample(text=text, spans=tuple(spans)))
    return PublicDataset(
        name="presidio-synthetic",
        citation="Presidio Evaluator (PresidioSentenceFaker) synthetic generator.",
        samples=tuple(samples),
    )


