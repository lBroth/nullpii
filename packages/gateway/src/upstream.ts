/**
 * Tiny wrapper around `fetch` for the upstream call. Surfaces both the
 * raw `Response` (so the route handler can mirror status + headers) and
 * the parsed body. Exposed as an injectable `Fetch` so tests can swap
 * it for a mock.
 */
export type Fetch = (input: string, init: RequestInit) => Promise<Response>;

export interface UpstreamCall {
  readonly status: number;
  readonly headers: Headers;
  readonly text: string;
}

/** Which client headers reach an upstream: exact names, plus whole
 * families by prefix. Anything else the client sent is dropped —
 * keeping the upstream surface minimal reduces the chance of leaking
 * gateway-internal headers (`host`, `content-length`) into the
 * request. */
export interface HeaderForwardPolicy {
  readonly exact: readonly string[];
  readonly prefixes: readonly string[];
}

/** Headers we MUST forward to Anthropic. */
const FORWARD_HEADERS = [
  // Auth — `x-api-key` for console API keys, `authorization` for OAuth
  // bearer tokens (Claude Code subscription / Pro / Max login flow).
  // Either passes through verbatim so the client picks its own auth
  // mode without the gateway caring.
  'x-api-key',
  'authorization',
  // Anthropic API version + beta opt-ins.
  'anthropic-version',
  'anthropic-beta',
  // Client identifiers used by Anthropic to route rate limits, debug
  // telemetry, and feature-gate flags. Forwarding keeps Claude Code /
  // SDK clients indistinguishable from a direct upstream call.
  'user-agent',
  'x-app',
];
/** Header-name prefixes whose entire family is forwarded. The
 * Anthropic SDK adds `x-stainless-*` telemetry fields as it evolves;
 * match by prefix so the allowlist doesn't drift behind new SDK
 * releases. Same safety profile as `FORWARD_HEADERS`. */
const FORWARD_HEADER_PREFIXES = ['x-stainless-'];

/** Default policy: the Anthropic Messages API. */
const ANTHROPIC_HEADER_POLICY: HeaderForwardPolicy = {
  exact: FORWARD_HEADERS,
  prefixes: FORWARD_HEADER_PREFIXES,
};

/** OpenAI Chat Completions: bearer auth, organization and project
 * scoping, beta opt-ins, and the client identifiers. The OpenAI SDKs
 * are generated by the same toolchain as Anthropic's and send the same
 * `x-stainless-*` telemetry family. */
export const OPENAI_HEADER_POLICY: HeaderForwardPolicy = {
  exact: ['authorization', 'openai-organization', 'openai-project', 'openai-beta', 'user-agent'],
  prefixes: ['x-stainless-'],
};

/**
 * Copy the allowlisted client headers into a fresh upstream header set,
 * with `content-type: application/json`. Header values are copied, never
 * logged.
 *
 * @param reqHeaders - the incoming request headers (Fastify / Node shape).
 * @param policy - which headers to keep; defaults to the Anthropic set.
 */
export function buildUpstreamHeaders(
  reqHeaders: Record<string, string | string[] | undefined>,
  policy: HeaderForwardPolicy = ANTHROPIC_HEADER_POLICY,
): Record<string, string> {
  const out: Record<string, string> = { 'content-type': 'application/json' };
  const exact = new Set(policy.exact);
  for (const [name, v] of Object.entries(reqHeaders)) {
    const lower = name.toLowerCase();
    const matchesExact = exact.has(lower);
    const matchesPrefix = policy.prefixes.some((p) => lower.startsWith(p));
    if (!matchesExact && !matchesPrefix) continue;
    if (typeof v === 'string') out[lower] = v;
    else if (Array.isArray(v) && v.length > 0 && typeof v[0] === 'string') out[lower] = v[0];
  }
  return out;
}

/** Extract the `?query` suffix from a Fastify-provided request URL.
 * Returns `''` if no query string is present. Routes forward this
 * verbatim so the upstream sees the same feature-gate flags
 * (`?beta=true`, etc.) the client sent. */
export function extractQuery(url: string): string {
  const i = url.indexOf('?');
  return i === -1 ? '' : url.slice(i);
}

/** POST `body` as JSON to `${upstreamBaseUrl}${path}` and read the whole
 * response as text. Used by the non-streaming paths of every route. */
export async function forwardToUpstream(
  fetchImpl: Fetch,
  upstreamBaseUrl: string,
  path: string,
  body: unknown,
  headers: Record<string, string>,
): Promise<UpstreamCall> {
  const res = await fetchImpl(`${upstreamBaseUrl}${path}`, {
    method: 'POST',
    headers,
    body: JSON.stringify(body),
  });
  const text = await res.text();
  return { status: res.status, headers: res.headers, text };
}
